let activeLanguage = 'zh-CN';

export function detectSystemLanguage() {
  const language = globalThis.navigator?.language || globalThis.navigator?.languages?.[0] || 'zh-CN';
  return String(language).toLowerCase().startsWith('zh') ? 'zh-CN' : 'en';
}

export function resolveLanguage(preference = 'system') {
  if (preference === 'zh-CN' || preference === 'en') return preference;
  return detectSystemLanguage();
}

export function applyLanguage(preference = 'system') {
  activeLanguage = resolveLanguage(preference);
  if (typeof document !== 'undefined') {
    document.documentElement.lang = activeLanguage;
    document.documentElement.dataset.language = activeLanguage;
    document.documentElement.dataset.languagePreference = preference;
    translateDocument(document);
  }
  return activeLanguage;
}

export function translateDocument(root = document) {
  if (!root?.querySelectorAll) return;
  root.querySelectorAll('[data-i18n]').forEach(node => {
    node.textContent = t(node.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-title]').forEach(node => {
    node.setAttribute('title', t(node.dataset.i18nTitle));
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach(node => {
    node.setAttribute('placeholder', t(node.dataset.i18nPlaceholder));
  });
  root.querySelectorAll('[data-i18n-aria-label]').forEach(node => {
    node.setAttribute('aria-label', t(node.dataset.i18nAriaLabel));
  });
}

export function getLanguage() {
  return activeLanguage;
}

export function t(key, variables = {}) {
  const dictionary = MESSAGES[activeLanguage] || MESSAGES['zh-CN'];
  const template = dictionary[key] ?? MESSAGES['zh-CN'][key] ?? key;
  return String(template).replace(/\{(\w+)\}/g, (_, name) => String(variables[name] ?? ''));
}

export function getLanguageOptions() {
  return LANGUAGE_OPTIONS.map(option => ({
    value: option.value,
    label: t(option.labelKey),
  }));
}

